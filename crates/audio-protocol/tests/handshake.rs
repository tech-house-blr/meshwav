#[test]
fn retransmitted_msg1_gets_the_same_reply_and_duplicate_msg3_is_ignored() {
    let agent = kp(1);
    let dev = kp(9);
    let mut srv = Server::new(agent.clone(), vec![Authorized { public: dev.public, name: "x".into() }]);
    let mut ini = Initiator::new(&dev, None, Some(agent.public)).unwrap();
    let f1 = frame(KIND_XX, 3, 1, &ini.write_msg1().unwrap());
    let Outcome::Reply(a) = srv.handle(addr(1), &f1, 0) else { panic!() };
    let Outcome::Reply(b) = srv.handle(addr(1), &f1, 10) else { panic!() };
    assert_eq!(a, b);
    ini.read_msg2(parse_frame(&a).unwrap().body).unwrap();
    let f3 = frame(KIND_XX, 3, 3, &ini.write_msg3("p").unwrap());
    assert!(matches!(srv.handle(addr(1), &f3, 20), Outcome::Established { .. }));
    assert!(matches!(srv.handle(addr(1), &f3, 30), Outcome::None), "duplicate msg3");
    assert!(matches!(srv.handle(addr(1), &f1, 40), Outcome::None), "msg1 after completion");
}

#[test]
fn msg3_from_another_address_or_tampered_is_rejected() {
    let agent = kp(1);
    let dev = kp(9);
    let mut srv = Server::new(agent.clone(), vec![Authorized { public: dev.public, name: "x".into() }]);
    let mut ini = Initiator::new(&dev, None, Some(agent.public)).unwrap();
    let Outcome::Reply(r2) = srv.handle(addr(1), &frame(KIND_XX, 3, 1, &ini.write_msg1().unwrap()), 0) else { panic!() };
    ini.read_msg2(parse_frame(&r2).unwrap().body).unwrap();
    let m3 = ini.write_msg3("p").unwrap();
    assert!(matches!(srv.handle(addr(2), &frame(KIND_XX, 3, 3, &m3), 5), Outcome::None), "other source address");
    let mut bad = m3.clone();
    bad[10] ^= 1;
    assert!(matches!(srv.handle(addr(1), &frame(KIND_XX, 3, 3, &bad), 6), Outcome::Rejected(_)));
    // the pending entry is consumed by the failed attempt
    assert!(matches!(srv.handle(addr(1), &frame(KIND_XX, 3, 3, &m3), 7), Outcome::None));
}

#[test]
fn pending_handshakes_are_capped_expire_and_msg1_is_rate_limited() {
    let agent = kp(1);
    let mut srv = Server::new(agent.clone(), vec![]);
    let m1 = |i: u32| {
        let mut ini = Initiator::new(&kp(9), None, None).unwrap();
        frame(KIND_XX, i, 1, &ini.write_msg1().unwrap())
    };
    let mut replies = 0;
    for i in 0..40 {
        if matches!(srv.handle(addr(1000 + i as u16), &m1(i), 0), Outcome::Reply(_)) {
            replies += 1;
        }
    }
    assert_eq!(replies, MAX_PENDING, "pending table is bounded");
    // after the pending TTL the table drains and new handshakes are served again
    assert!(matches!(srv.handle(addr(5000), &m1(99), PENDING_TTL_MS + 1000), Outcome::Reply(_)));
    // rate limit: more than MSG1_PER_SEC msg1 in one second are dropped even when slots are free
    let mut srv = Server::new(agent, vec![]);
    let mut served = 0;
    for i in 0..(MSG1_PER_SEC + 20) {
        let t = 10_000 + i as u64; // same second
        let out = srv.handle(addr(100 + i as u16), &m1(i), t);
        if matches!(out, Outcome::Reply(_)) {
            served += 1;
        }
        srv.handle(addr(100 + i as u16), &frame(KIND_XX, i, 3, &[0; 10]), t); // free the slot
    }
    assert_eq!(served, MSG1_PER_SEC);
}

